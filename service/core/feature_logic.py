# Пороги категории приоритета — подтверждены реальным кодом ПУЛЬС (frontend/src/api.ts)
PRIORITY_LOW_MAX = 40
PRIORITY_MEDIUM_MAX = 70


def priority_category(score: float) -> str:
    if score is None:
        return "неизвестно"
    if score < PRIORITY_LOW_MAX:
        return "низкий"
    elif score <= PRIORITY_MEDIUM_MAX:
        return "средний"
    return "высокий"
