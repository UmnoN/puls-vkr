"""
EDA + Feature Engineering для датасета сделок проекта ПУЛЬС.
Разбито на понятные блоки, с комментариями на каждом шаге.
"""

import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")  # рисуем графики в файлы, не в окно
import matplotlib.pyplot as plt

plt.rcParams["font.size"] = 10

# ============================================================
# ШАГ 0. Загружаем данные
# ============================================================
df = pd.read_csv("сделки_очищено.csv")

# Даты пока хранятся как текст "31.03.2026 11:28" — превращаем в настоящие даты,
# чтобы с ними можно было считать разницу (сколько дней прошло и т.д.)
df["Дата создания"] = pd.to_datetime(df["Дата создания"], format="%d.%m.%Y %H:%M")
df["Дата изменения"] = pd.to_datetime(df["Дата изменения"], format="%d.%m.%Y %H:%M")

print("Всего строк:", len(df))
print("Новых клиентов:", (~df["is_existing_client"]).sum())
print("Действующих клиентов:", df["is_existing_client"].sum())

# ============================================================
# ШАГ 1. EDA — распределение стадий по сегментам
# ============================================================
# Смотрим отдельно на "новых" (на них строим модель) и "действующих" (только описательно)
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

for ax, flag, title in [
    (axes[0], False, "Новые клиенты (574) — стадии сделки"),
    (axes[1], True, "Действующие клиенты (203) — служебная метка*"),
]:
    counts = df[df["is_existing_client"] == flag]["Стадия сделки"].value_counts()
    counts.plot(kind="barh", ax=ax, color="#4C72B0")
    ax.set_title(title)
    ax.invert_yaxis()
    ax.set_xlabel("Количество сделок")

fig.text(
    0.5, -0.02,
    "* У действующих клиентов 'Стадия' — служебная метка вовлечённости менеджера,\n"
    "а НЕ статус успеха сделки. Все действующие клиенты (кроме источника «Холдинг»)\n"
    "— исторически успешные, платящие клиенты, независимо от текущей стадии.",
    ha="center", fontsize=9, style="italic",
)

plt.tight_layout()
plt.savefig("eda_plots/01_stages_by_segment.png", dpi=120)
plt.close()
print("Сохранён график: 01_stages_by_segment.png")

# ============================================================
# ШАГ 2. EDA — Потенциал и ФОТ (много выбросов, поэтому смотрим в лог-масштабе)
# ============================================================
new_df = df[~df["is_existing_client"]].copy()

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

# Потенциал: много нулей и есть огромные значения (до 254 млн) — берём log1p,
