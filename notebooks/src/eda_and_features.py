plt.tight_layout()
plt.savefig("eda_plots/02_potential_payroll_distribution.png", dpi=120)
plt.close()
print("Сохранён график: 02_potential_payroll_distribution.png")

# ============================================================
# ШАГ 3. FEATURE ENGINEERING — новые признаки, согласованные в дельте и по методике ПУЛЬС
# ============================================================

# --- 3.1. Признаки по датам (уже согласованы в дельте) ---
# Сколько дней сделка "варится" без движения — от создания до последнего изменения
df["days_in_pipeline"] = (df["Дата изменения"] - df["Дата создания"]).dt.days

# Сколько дней сделке вообще, если считать от сегодняшнего дня (по последней дате в файле)
snapshot_date = df["Дата изменения"].max()
df["deal_age_days"] = (snapshot_date - df["Дата создания"]).dt.days

# --- 3.2. Порядок стадий — подтверждён кодом ПУЛЬС (stage_mapping.py, STAGE_ORDER) ---
STAGE_ORDER = {
    "СоцКом анализ": 1,
    "Установка контакта": 2,
    "Стратегия": 3,
    "Продажа": 4,
    "Возражения": 5,
    "Подписание Договора": 6,
    "Получение взносов": 7,
    "Сделка завершена с успехом": 8,
    "Сделка не состоялась": 8,  # терминальная, вне линейной последовательности
}
df["stage_number"] = df["Стадия сделки"].map(STAGE_ORDER)

# Подготовительная часть воронки (1-3) vs активная (4-7), терминал считаем активным для флага
PREP_STAGES = {"СоцКом анализ", "Установка контакта", "Стратегия"}
df["prep_or_active_flag"] = np.where(
    df["Стадия сделки"].isin(PREP_STAGES), "prep", "active"
)

# --- 3.3. Эвристика вероятности по стадии — ТОЛЬКО для новых клиентов ---
# ВАЖНО (уточнение владельца проекта): у действующих клиентов поле "Стадия сделки"
# переиспользуется как служебная метка ("ведёт ли менеджер активную работу прямо
# сейчас"), а не как реальный статус успеха сделки. CRM кастомная, доработать
# отдельную воронку для действующих клиентов пока нельзя (нет ресурсов разработки),
# поэтому статус "Сделка не состоялась" у действующего клиента означает "клиенту не
# уделяют внимание сейчас", а НЕ "сделка провалилась" — это принципиально другое.
# Поэтому priority_score/weighted_potential/reactivation_score считаем только для
# новых клиентов; у действующих эти поля не имеют смысла и оставляются пустыми (NaN).
STAGE_HEURISTIC_PCT = {
    "Сделка не состоялась": 0,
    "СоцКом анализ": 5,
    "Установка контакта": 10,
    "Стратегия": 20,
    "Продажа": 35,
    "Возражения": 45,
    "Подписание Договора": 70,
    "Получение взносов": 90,
    "Сделка завершена с успехом": 100,
}
df["priority_score"] = np.where(
    ~df["is_existing_client"], df["Стадия сделки"].map(STAGE_HEURISTIC_PCT), np.nan
)

# --- 3.4. Категория приоритета — пороги взяты из реального кода ПУЛЬС (frontend/src/api.ts) ---
def priority_category(score):
    if score < 40:
        return "низкий"
    elif score <= 70:
        return "средний"
    else:
        return "высокий"

df["priority_category"] = df["priority_score"].apply(
    lambda s: priority_category(s) if pd.notna(s) else np.nan
)

# --- 3.5. Взвешенный потенциал = Потенциал × Вероятность — тоже только для новых ---
df["weighted_potential"] = df["Потенциал"] * (df["priority_score"] / 100)

# --- 3.6. SPIN + презентация как бинарный флаг (по логике spin_presentation в scoring_core.py) ---
spin_col = "Файл и ссылка продажи (СПИН) (по колонке Продажа)"
presentation_col = "Файл и ссылка продажи (презентация нов.) (по колонке Продажа)"
df["spin_presentation_flag"] = ((df[spin_col] > 0) & (df[presentation_col] > 0)).astype(int)

# --- 3.7. "Свежесть" контакта — упрощённый аналог days_without_contact из ПУЛЬС ---
# У нас нет отдельного поля даты последней активности, поэтому берём "Дата изменения"
# как приближение (это огрубление, честно фиксируем в тексте ВКР как ограничение)
days_since_change = (snapshot_date - df["Дата изменения"]).dt.days
df["days_since_change_norm"] = np.clip(1 - days_since_change / 30, 0, 1)

# --- 3.8. Реактивация провальных сделок — ОТДЕЛЬНЫЙ трек, не часть priority_score ---
# Идея: "Сделка не состоялась" не значит "потеряна навсегда" (длинный бюджетный цикл,
# компания может вернуться через год). Но мешать провальные сделки с активной воронкой
# в одном priority_score нельзя — это разные действия менеджера ("работать сейчас" vs
# "попробовать вернуть через полгода"). Поэтому считаем отдельный балл, только для
# провальных, по давности провала: чем свежее "Сделка не состоялась" — тем выше шанс
# вернуть клиента. Окно — 365 дней (год), а не 30, т.к. ориентируемся на годовой
# бюджетный цикл клиента, а не на "теплоту" контакта по активной сделке.
FAILED_STAGE = "Сделка не состоялась"
# ВАЖНО: для действующих клиентов "Сделка не состоялась" — это НЕ провал,
# а служебная метка "менеджер сейчас не ведёт активную работу" (см. пояснение выше).
# Поэтому реактивация имеет смысл только для новых клиентов.
is_failed = (df["Стадия сделки"] == FAILED_STAGE) & (~df["is_existing_client"])

df["reactivation_score"] = np.nan  # для НЕ провальных сделок метрика не применима вовсе
df.loc[is_failed, "reactivation_score"] = (
    np.clip(1 - days_since_change[is_failed] / 365, 0, 1) * 100
)

# --- 3.9. Флаг "реальный успех" для ДЕЙСТВУЮЩИХ клиентов ---
# Уточнение владельца проекта: любой действующий клиент (кроме источника "Холдинг" —
# там неоднозначно, часто это просто управляющая компания без отдельного договора) —
# это реальная историческая история успеха, НЕЗАВИСИМО от текущей "Стадии сделки"
# (которая для действующих клиентов служебная, см. выше). Источник "Холдинг" исключаем.
df["is_genuine_existing_success"] = (
    df["is_existing_client"] & (df["Источник"] != "Холдинг")
)

# ============================================================
# ШАГ 4. Проверка результата — что получилось
# ============================================================
new_cols = [
    "days_in_pipeline", "deal_age_days", "stage_number", "prep_or_active_flag",
    "priority_score", "priority_category", "weighted_potential",
    "spin_presentation_flag", "days_since_change_norm", "reactivation_score",
]
print("\nНовые колонки:", new_cols)
print("\nПример на 5 случайных строках:")
print(df[["Стадия сделки"] + new_cols].sample(5, random_state=42).to_string())

print("\nРаспределение категорий приоритета (все 777 сделок):")
print(df["priority_category"].value_counts())

print("\nreactivation_score — только для провальных сделок (Сделка не состоялась):")
print(df.loc[df["Стадия сделки"] == "Сделка не состоялась", "reactivation_score"].describe())
print("Топ-5 самых перспективных для реактивации (свежепровалившиеся):")
print(
    df[df["Стадия сделки"] == "Сделка не состоялась"]
    .nlargest(5, "reactivation_score")[["Id", "Дата изменения", "reactivation_score"]]
    .to_string(index=False)
)

# ============================================================
# ШАГ 5. Сохраняем обогащённый датасет
# ============================================================
df.to_csv("сделки_с_признаками.csv", index=False)
print("\nСохранён файл: сделки_с_признаками.csv")
